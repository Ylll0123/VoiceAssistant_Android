/**
 * 思维方法类知识分组：怎么想、怎么决定、怎么说。
 *
 * ## 为什么单独一组
 * 这类问题没有唯一的「标准事实」，但有公认的**思考方法**。
 * 答案是按「先给结论 → 再说原因 → 最后给做法」写的，
 * 既直接回答了问题，也给学生一套能立刻照着做的步骤。
 * 这些条目同时会灌进本地小模型做问答对训练，
 * 模型学到的是「问句后面接一段有因果的话」，回答自然更像讲道理。
 */
object KbLogic {

    val entries: List<KnowledgeQA> by lazy {
        decide() + learn() + explain() + communicate() + concepts()
    }

