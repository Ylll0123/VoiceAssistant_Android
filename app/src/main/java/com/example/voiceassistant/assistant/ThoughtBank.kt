    /** 收尾钩子模板：`你是 bean：{t}` 里 {t} 换成用户的事 */
    val HOOKS = listOf(
        "你先说说看？",
        "你现在更偏向哪边？",
        "要不要往下试一步？",
        "我说的不一定对，你觉得呢？",
