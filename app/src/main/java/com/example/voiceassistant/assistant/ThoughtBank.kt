package com.example.voiceassistant.assistant

/**
 * 思维模式语料库：不会的问题该怎么「像 AI 一样有思路地回答」。
 *
 * ## 为什么需要它
 * 以前本地答不上来的句子只有三条出路：搜网络、让小模型拼一句、或者回一句固定的「我不懂」。
 * 用户不喜欢第二条（没逻辑），也不喜欢第三条（每次一样）。
 * 这里走的是第四条：**承认不知道，但给出一条可执行的思考路径**——
 * 这也是真人专家被问到自己不知道的事情时的做法。
 *
 * ## 组织方式
 * 每个模式（[com.example.voiceassistant.assistant.ReplyCrafter.Mode]）准备 4~6 套完整回答，
 * 回答里包含三段结构：
 * 1. **接住**：共情 / 复述用户的话（让他知道被听见了）；
 * 2. **给路径**：分点列出的分析框架，不编事实；
 * 3. **抛回来**：一个反问，把话头递回给用户，下一轮还能继续。
 *
 * `{t}` 是占位符，组装时会换成用户问的那件事本身。
 */
object ThoughtBank {

    // ------------------------------------------------------------------ 情绪承接

    /** 情绪类：先站在他那边，再给一个最小出口，最后问一句 */
    val EMOTION = listOf(
        "先说一句：会有这种感觉挺正常的，不是只有你一个人这样。{t}压在心里的时候，不用急着马上解决，能把它讲出来本身就是在处理。你要是愿意，跟我说说最早是从哪件小事开始的？",
        "我听到了。{t}这种状态拖久了很耗人，先别逼自己振作起来。给自己一个最小的出口就行——哪怕今天就做一件让你松一点点的小事。现在最让你堵得慌的是哪一块？",
        "听起来你现在确实不太好受。我不打算跟你说想开点，那话没什么用。更实际的做法是先分清：这件事里哪些是你能动的，哪些暂时动不了。能动的那一小部分，你想先从哪里开始？",
        "嗯，我大概能想象那种感觉。{t}之所以难熬，是因为它慢慢累积，等你发现的时候已经很累了。这种时候与其硬撑，不如先把节奏降下来一天。要不要我陪你把这件事拆开看看？",
        "我想先确认一下你的需要：你现在更想有人陪你聊聊，还是想一起想个办法？这两种情况，我接下来说的话会不太一样。",
        "这种时候最忌讳给自己下结论。情绪更像一个信号，它在告诉你某个地方失衡了——至于是哪里，我们可以一点点排查。你最近睡得还行吗？"
    )

    /**
     * 情绪低落专用（用户明确在表达「不开心 / 不高兴 / 提不起劲」这类**否定式情绪**）。
     *
     * 和 [EMOTION] 分开的理由：通用情绪模板偏中性，用在「我不高兴」上听着像在打官腔；
     * 这一组是直接承认「你现在不开心」，而不是笼统地说「有这种感觉很正常」。
     */
    val DOWN = listOf(
        "听出来了，你现在的心情确实好不起来。先说一句：这不是你的问题，情绪低落本身不需要理由，也不需要马上被解决。愿意的话说说，是从什么时候开始变成这样的？",
        "嗯，这种「说不上哪里不对但就是提不起劲」的状态最磨人。我不会劝你想开点，那没用。如果只能做一件事，今天就挑一件最小、最容易完成的事做掉——哪怕只是出门走十分钟。你现在最不想面对的是什么？",
        "我不打算把你现在的状态美化成「会好的」。现在更重要的是搞清楚它卡在哪：是某件具体的事，还是一种说不清的疲惫？这两种的处理方式完全不同。你觉得更像哪一种？",
        "人在低落的时候最容易对自己下结论，比如「我怎么这么没用」。但情绪更像天气，它是会变的，不能用来定义你这个人。要不要先把让你堵得慌的那件事说给我听？",
        "我在听。你不需要马上振作，也不需要把话说得很完整，想到哪说哪就行。要不要先休息一会儿，还是边聊边理？",
        "不开心的时候，最有效的往往不是分析，而是先把它从脑子里挪出来。你可以把它讲给我听，讲完我们再看哪一部分是能动的。"
    )

    // ------------------------------------------------------------------ 比较取舍

    /** A 和 B 怎么比：先定「尺子」，再谈好坏 */
    val COMPARE = listOf(
        "{t}这种比较，我建议先别急着挑结果，而是先定用什么尺子量。三个维度通常就够：成本（时间和钱）、风险（最坏情况）、契合度（是不是你真正想要的）。把这三样填进去，答案经常自己就出来了。",
        "我们不猜，换个做法：把两者各自最让你心动的一点、和最让你犹豫的一点写出来。犹豫的那条往往才是真正在影响你的因素。你要不要先说一个？",
        "{t}没有绝对的好坏，只有此刻合不合适。所以关键问题变成：你现在处在哪一步、接下来三个月最缺什么。缺什么补什么，那个选项自然就排在前面。",
        "我给你一个判断法：想象你选了其中一个，三个月后的你会后悔吗？再想象另一个。两个答案里后悔感更小的，通常更接近你的本心。你也可以直接告诉我两边的名字，我帮你列。",
        "比答案没有意义，比「代价」才有意义。{t}具体要看你最不能接受哪一种代价——是慢、是贵、还是不确定？把这个说出来，我就能帮你定。"
    )

    // ------------------------------------------------------------------ 归因

    /** 为什么会这样：给找原因的顺序 + 验证方法，不瞎给结论 */
    val CAUSE = listOf(
        "{t}的确切成因我不想瞎编，这类问题通常从三个角度找：一、直接触发条件——是最近才变的，还是一直这样；二、长期影响因素——哪些背景条件一直在起作用；三、反例验证——有没有时候明明条件相同却没发生，那就能排除掉一个解释。你把背景再说细一点，我帮你缩小范围。",
        "找原因有个笨办法但很有效：先把是什么时候开始的定下来。时间点一定，前后的变量就少了很多。你还记得第一次出现是在什么情况下吗？",
        "{t}通常不是单一原因。我习惯把可能拆成三层：表层是直接的触发事件，中层是习惯或环境，底层是长期性的结构问题。多数人只在表层打转，所以事情才会反复出现。你觉得哪一层更像你现在的情况？",
        "我不想给你一个听起来合理但没根据的解释。换个思路：我们把它反过来问——什么情况下它不会发生？把不会发生的条件列出来，真正的原因基本就浮出来了。",
        "这件事我给不了百分百准确的答案，但我能告诉你怎么验证：挑一个你怀疑的因素，试着改变它一周，看情况有没有变化。有变化说明方向找对了，没变化就换下一个。你最怀疑的是哪个？"
    )

    // ------------------------------------------------------------------ 做选择

    /** 该不该 / 要不要：给决策顺序 */
    val CHOICE = listOf(
        "{t}这种选择题，按三步想比反复纠结有用：一、先定目的——你想通过它得到什么，目的清楚了选项通常自己少一半；二、再看代价——最坏的结果你能不能接受，能接受就去做；三、最后留退路——能不能先小规模试一次，不行再退回来。你现在最在意的是哪一步？",
        "你可以试个简单的检验：想象做完这个选择，五天后你会后悔吗？五个月后呢？如果两个答案不一样，按五个月那个走——短期情绪经常会骗人。",
        "先问一个更实际的问题：这个决定能不能先试一小步？能试的就先试，只有试不了的决定才需要反复权衡。如果{t}可以事先试一小步，我会建议你今天就试。",
        "你现在卡住多半不是不会选，而是缺一条关键信息。我们把它找出来：关于{t}，你现在最不确定的是什么？那条信息往往就是决定胜负的东西。",
        "拿张纸画两列：左边写做了之后最坏会怎样、最好会怎样；右边写不做的同样两项。写完你会发现自己其实已经有倾向了，只是还没承认。你要不要先说说你心里的倾向在哪边？",
        "别把它当成一次性的终审判决。多数选择事后都能调整，真正不可挽回的很少。所以{t}：选那个就算错了也能学到东西的方向，通常都不会太亏。"
    )

    // ------------------------------------------------------------------ 求办法

    /** 怎么办：先把「一个大问题」拆成「今天能做的一个动作」 */
    val METHOD = listOf(
        "{t}看起来难，多半是因为它不是一个问题，是几件事叠在一起。我们按四步拆：一、说清现状，现在具体卡在哪一步；二、把目标缩小到这周能做完的一件小事；三、选一个今天就能动的最小动作，别等；四、做完复盘，再决定要不要调整。你先说第一步：卡在哪了？",
        "与其想怎么解决{t}，不如先想明天早上我能做的第一个动作是什么。一个大问题被拆到这一步，难度通常会掉一半。你明天方便做的最小动作是什么？",
        "这类事有个规律：难在启动，不在坚持。所以别给自己排大计划，先做一个五分钟版本。做完五分钟再决定要不要继续——多数时候你会继续下去。要不要现在就先定个五分钟版本？",
        "我建议你换个问法：把怎么才能{t}换成谁已经做成过、他第一步做了什么。找得到一个具体的样板，比听十条道理有用。你身边有没有类似的人？",
        "需要先认清一件事：如果没有反馈，重复一万次也不会进步。所以{t}的关键不是多练，而是每次之后能知道哪里不对。你能不能找到一个能给你反馈的人或者标准？",
        "先别急着优化方法，把这件事放进时间表。多数做不成的事不是因为方法差，而是没有固定时间。我们先定一个固定时段，方法往往会自己长出来。你一天里哪段时间最不容易被打断？"
    )

    // ------------------------------------------------------------------ 求看法

    /** 你觉得呢：给判断的三层，再反问用户 */
    val OPINION = listOf(
        "说我的看法可以，但我不想给空话。{t}我习惯分三层看：一、事实是什么（有证据的部分）；二、影响谁（对最关键的人或事带来什么）；三、愿意付什么代价换这个结果。这三点你先补一下，我就能给你一个站得住的判断。",
        "我的第一反应是：这件事要看你追求的是短期舒服还是长期划算。两个目标没有高下，但混在一起就会拧巴。{t}，你更在意哪个？",
        "如果只说一句：我不太建议你现在就下结论，因为信息还不够。但在现有信息下，我会倾向于那个失败了也能留下东西的选项——这是风险最低的一种思考方式。",
        "说实话，外人的判断代替不了你自己的处境。我能做的是帮你把隐含的假设挖出来：{t}这件事里，你默认接受了什么前提？那个前提一旦松动，答案可能就变了。",
        "我有个偏见你可以参考：凡是那些需要反复说服自己其实也挺好的选择，多半心里已经有了答案。你觉得这条用在{t}上准不准？"
    )

    // ------------------------------------------------------------------ 求讲解

    /** 讲讲 XX：先讲框架，再让用户选往哪深入 */
    val EXPLAIN = listOf(
        "{t}我可以按一句话版本加为什么来讲：先给一句话的说法，再补充关键细节，最后说一个容易混淆的地方。你更想听通俗版，还是正式一点的版本？",
        "讲{t}之前先确认边界：我只能给你一个通用理解，细节得看具体场景。通用的说法是这样——先弄清它是为了解决什么问题出现的，再看它由哪几部分组成，最后看它什么时候会失效。这三步理解了，基本就算懂了。",
        "别急着背定义。理解{t}最有效的方式，是找一个你已经熟悉的东西跟它类比。你有没有觉得它有点像什么？说出来，我们顺着那个类比往下走。",
        "关于{t}，我怕讲得不准确，所以先给框架：它存在的目的、它靠什么机制工作、以及它的代价。你告诉我想深入哪一部分，我就把那部分讲细。",
        "{t}这个话题讲深了很长。我建议先抓主干：一句话说清它是什么，再举一个生活里的例子，最后留一个「它在哪会失效」的提醒。要不要我从其中一个开始？"
    )

    // ------------------------------------------------------------------ 不知道的事实

    /** 事实类但本地没有答案：**明确承认不知道**，然后给查证路径 */
    val FACT = listOf(
        "{t}——这个我没有可靠的把握，不想随口编一个答案糊弄你。我可以做的是帮你定方向：你想知道它是为了做决定，还是只是好奇？目的不同，我帮你的方式也不一样。",
        "这一条我不太确定，说错比不说更糟。不过我可以给你一个查证的思路：先看有没有权威来源（官方、学术、原始数据），再看有没有相反的说法，两边都看过才算数。需要我陪你把线索列出来吗？",
        "关于{t}，我的确没有准确的答案。与其给你一个听起来像但不靠谱的说法，不如我们先把它拆成你已经知道的几个部分，从已知推未知，看能推到哪一步。",
        "老实说，这个我不知道。但我想提醒一点：这类问题很容易查到自相矛盾的答案，所以最稳的办法是找原始出处，而不是二手解读。你现在是想快速要个大概，还是要准确？",
        "{t}——我承认这一条超出了我能确定的范围。你要是愿意多给点线索（是谁说的、在什么场合看到的、大概什么时候），我可以跟你一起判断哪条信息更可信。"
    )

    // ------------------------------------------------------------------ 完全没听懂

    /** 没听懂 / 没头绪：不说「抱歉我不懂」这一句，而是换着花样把话头接住 */
    val UNKNOWN = listOf(
