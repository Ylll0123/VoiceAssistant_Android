    /** 所有回答模板，供小模型当训练语料（让模型也学到这种说话方式） */
    fun allSentences(): List<String> =
        EMOTION + DOWN + COMPARE + CAUSE + CHOICE + METHOD + OPINION + EXPLAIN + FACT + UNKNOWN
